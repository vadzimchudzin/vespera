class FakeWS {
  constructor(url) { this.url = url; this.sent = []; this.readyState = 0; FakeWS.all.push(this); }
  send(s) { this.sent.push(typeof s === "string" ? s : JSON.stringify(s)); }
  close() { this.readyState = 3; this.closedByClient = true; }
  open() { this.readyState = 1; this.onopen && this.onopen({}); }
  msg(data) { this.onmessage && this.onmessage({ data: typeof data === "string" ? data : JSON.stringify(data) }); }
  drop(code = 1006) { this.readyState = 3; this.onclose && this.onclose({ code, reason: "" }); }
}

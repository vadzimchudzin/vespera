// A Chainlink gap the history filled is listed as filled; one with seconds missing counts over the limit.
async function filledGapTests() {
  const dir = tmp();
  const s = await new Store({ dir }).open();
  const t0 = Date.UTC(2026, 10, 4, 16, 0, 0);
  const point = (sym, ts) => ({ timestamp: ts, value: 1 });
  for (let k = 0; k <= 60; k += 1) {
    if (k > 20 && k < 40) continue;   // live points stop between 20 s and 40 s …
    for (const sym of ["btc/usd", "eth/usd"]) s.write("chainlink", t0 + k * 1000 + 300, { topic: "crypto_prices_twap_sixty", payload: { symbol: sym, ...point(sym, t0 + k * 1000) } });
  }
  // … and the history after the reconnect brings 21–39 s back for btc and eth, but eth only from 25 s on for the second gap
  for (const sym of ["btc/usd", "eth/usd"]) {
    s.write("chainlink", t0 + 41000, { topic: "crypto_prices_twap_sixty", type: "subscribe", payload: { symbol: sym, data: Array.from({ length: 19 }, (_, i) => point(sym, t0 + (21 + i) * 1000)) } });
  }
  s.addGap({ feed: "chainlink", kind: "silence", from: t0 + 20300, to: t0 + 40300, ms: 20000 });
  s.addGap({ feed: "chainlink", kind: "silence", from: t0 + 70300, to: t0 + 80300, ms: 10000 });
  s.addGap({ feed: "clob", shard: 2, kind: "disconnect", from: t0 + 5000, to: t0 + 12000, ms: 7000 });
  await s.close();
  const r = await checkDay({ dir, day: "2026-11-04", now: t0 + HOUR });
  assert.deepStrictEqual([r.gaps.chainlink.n, r.gaps.chainlink.over, r.gaps.chainlink.filled], [2, 1, 1]);
  assert.deepStrictEqual(r.gaps.chainlink.longest.map((g) => [g.ms, !!g.filled]), [[20000, true], [10000, false]]);
  assert.deepStrictEqual([r.gaps.clob.over, r.gaps.clob.filled, r.gaps.clob.longest[0].shard], [1, 0, 2], "the CLOB has no history to fill from");
}

// The rebuild rules on hand-made data: Chainlink TWAP at exact seconds; Binance trades on both sides of a boundary.
function rebuildTests() {
  const idx = new Index();
  const start = Date.UTC(2026, 10, 4, 16), end = start + HOUR;
  idx._chainlink({ topic: "crypto_prices_twap_sixty", payload: { symbol: "btc/usd", data: [{ timestamp: start, value: 100 }, { timestamp: end, value: 100 }] } });
  const tw = { asset: "btc", rule: "chainlink-twap60", start, end };
  assert.deepStrictEqual(rebuild(tw, idx, []).ours, "Up", "equal → Up (≥)");
  assert.strictEqual(rebuild({ ...tw, end: end + 1000 }, idx, []).ours, null, "no point at the exact second → no data");
  const trades = [[start - 3000, 50, 1], [start + 500, 51, 2], [start + 900, 52, 3], [end - 2000, 49, 4], [end - 1000, 53, 5], [end + 2000, 60, 6]];
  for (const [T, p, a] of trades) idx._trade("binance", { e: "aggTrade", s: "BTCUSDT", T, p: String(p), a });
  const h = { asset: "btc", rule: "binance-1h", start, end };
  assert.deepStrictEqual(rebuild(h, idx, []), { ours: "Up", k: 51, f: 53, sure: true, note: null });
  assert.strictEqual(rebuild(h, idx, [{ feed: "binance", from: end - 4000, to: end - 3000, ms: 1000 }]).sure, false, "a gap at the boundary: unsure");
  assert.strictEqual(rebuild({ ...h, start: start + 600 }, idx, []).ours, null, "boundaries on whole minutes only");
  const late = new Index();
  late._trade("binance", { e: "aggTrade", s: "BTCUSDT", T: start + 500, p: "51", a: 1 });
  late._trade("binance", { e: "aggTrade", s: "BTCUSDT", T: end + 1000, p: "51", a: 2 });
  late._trade("binance", { e: "aggTrade", s: "BTCUSDT", T: end - 1000, p: "51", a: 3 });
  assert.strictEqual(rebuild(h, late, []).ours, null, "no trade recorded before the start: the open is unproven");
  const d = new Index(), dStart = Date.UTC(2026, 10, 3, 17), dEnd = dStart + 86400000;
  for (const [T, p, a] of [[dStart + 59000, 100, 1], [dStart + 61000, 1, 2], [dEnd + 59500, 100, 3], [dEnd + 60500, 1, 4]]) d._trade("binance", { e: "aggTrade", s: "BTCUSDT", T, p: String(p), a });
  const daily = { asset: "btc", rule: "binance-1m-close", start: dStart, end: dEnd };
  assert.deepStrictEqual([rebuild(daily, d, []).ours, rebuild(daily, d, []).k, rebuild(daily, d, []).f], ["50-50", 100, 100], "the 1-minute closes at noon ET: equal → 50-50");
  const us = new Index();
  for (const [T, p, a] of [[start - 1000, 1, 1], [start + 1000, 2, 2], [end - 1000, 1, 3], [end + 1000, 5, 4]]) us._trade("binanceus", { e: "aggTrade", s: "BTCUSDT", T, p: String(p), a });
  const r = rebuild(h, us, []);
  assert.deepStrictEqual([r.ours, r.sure, /Binance\.US/.test(r.note)], ["Down", false, true], "Binance.US: another exchange, unsure");
  assert.strictEqual(rebuild({ asset: "btc", rule: "unknown", start, end }, idx, []).ours, null);
}


"use strict";
const assert = require("node:assert/strict");
const { applySale, positionReady } = require("./saleAccounting");
const bet = { clientOrderId: "buy", tokenId: "123", shares: "10.000001", sizeUsd: "4.000000", feeUsd: "0.040000" };
const part = { orderId: "sell-1", tokenId: "123", shares: "6.000000", proceedsUsd: "3.000000", feeUsd: "0.100000" };
assert.equal(positionReady(bet),true);
assert.equal(positionReady({ ...bet, feeUsd:null }),false);
const result = applySale(bet, part);
assert.equal(result.complete, false);
assert.equal(result.bet.shares, "4.000001");
assert.equal(result.bet.saleProceedsUsd, "3.000000");
const end = applySale(result.bet, { orderId: "sell-2", tokenId: "123", shares: "4.000001", proceedsUsd: "2.000001", feeUsd: "0.100000" });
assert.equal(end.complete, true);
assert.equal(end.settled.pnl, "0.76");
assert.equal(end.settled.feeUsd, "0.240000");
assert.equal(end.settled.status, "win");
assert.equal(applySale(bet, { ...part, shares: "11" }).ok, false);
assert.equal(applySale(bet, { ...part, tokenId: "other" }).ok, false);
assert.equal(applySale({ ...bet, feeUsd: null }, part).ok, false, "unknown entry fee is never treated as zero");
assert.equal(applySale(bet, { ...part, feeUsd: "4" }).ok, false);
assert.equal(applySale(bet, { ...part, shares: "6.0000001" }).ok, false);
assert.equal(bet.shares, "10.000001", "original bet remains unchanged");
const loss = applySale({ ...bet, shares: "6" }, part);
assert.equal(loss.settled.pnl, "-1.14");
console.log("Sale accounting tests ok");
